#!/usr/bin/env bash
#
# Provision the shared local test database to migrations head.
#
# Live-DB suites ASSERT the schema they need (assertSchemaReady) rather than
# re-applying migration SQL in beforeAll — run-time DDL takes ACCESS EXCLUSIVE
# locks that deadlock against sibling suites' row locks (#573). That makes this
# script the single owner of "the test DB is at head": run it once after
# creating the database and again whenever a migration lands.
#
# DESTRUCTIVE + repeatable: the migration chain is not re-runnable against a
# populated database (001 creates its tables unconditionally), so this drops and
# recreates schema `public` before applying it. That is deliberate — the value
# of this script is a DETERMINISTIC at-head schema, which is what lets suites
# assert instead of apply. It refuses any host that is not localhost.
#
# CROSS-PROCESS SAFETY (#877): the whole run executes in ONE psql session that
# FIRST takes the exclusive form of the live-DB advisory lock —
# `pg_advisory_lock(hashtext('repworth_live_db_integration'))`, the same key
# the DDL integration suites hold (src/lib/shared/__tests__/helpers/
# live-db-lock.ts) and that ci:rls-audit's live check takes in shared form. A
# sibling worktree's gate can therefore never observe a half-dropped schema
# from this script, and this script waits for lock holders instead of dropping
# `public` beneath them. The lock lives IN the session that performs the DDL:
# killing the session releases the lock and stops the work in the same
# instant, and there is no wrapper entry path that could bypass it. Note the
# guarantee's precise shape: the chain autocommits per statement (several
# migrations use CREATE INDEX CONCURRENTLY), so an interrupted run leaves
# already-committed DDL behind — what cannot happen is DDL CONTINUING after
# the lock releases. The `test_meta.provision` marker (written as the LAST
# statement, cleared first) is how readers tell a completed provision from an
# interrupted or stale one: it records a hash of the ordered bootstrap +
# migration contents.
#
# Single-session hygiene: migration 103 deliberately leaves a SESSION-level
# `SET search_path`, safe only when each file ran in its own psql process, and
# several migrations leave bare `lock_timeout` behind — so the driver emits
# `RESET ALL;` after the bootstrap and after EVERY migration include.
# (`RESET ALL` restores configuration parameters; it does not release the
# session's advisory lock.)
#
# POSTGRES MAJOR (#1379): this script is the single owner of the test DB's
# PostgreSQL major, REQUIRED_PG_MAJOR below — the major both Supabase projects
# run. The container is `postgres:17`, CI's service image
# (`.github/workflows/ci.yml`, `e2e.yml`) is the same, and the driver refuses a
# server below it BEFORE any DDL. Developer default: container
# `repworth-testdb-pg17` on port 5500 (create one per
# docs/runbooks/e2e-local-setup.md). A lower major is not a harmless drift:
# migration 122's MAINTAIN branch is version-guarded, so a PG16 container
# passes its suite while asserting less. assertSchemaReady
# (src/lib/shared/__tests__/helpers/schema-ready.ts) re-checks the same floor
# at suite time; its unit test (schema-ready.test.ts, beside it) pins the two
# spellings and the CI images to this value.
#
#   pnpm test:db:setup
#   scripts/test-db-setup.sh --print-driver   # emit the driver SQL, run nothing
#
# Reads TEST_DATABASE_POOL_URL from the environment, falling back to .env.local.
set -euo pipefail
cd "$(dirname "$0")/.."

# Byte-for-byte with LIVE_DB_LOCK_KEY in live-db-lock.ts and the shared
# acquisition in scripts/ci/rls-audit.ts — pinned by
# scripts/ci/__tests__/test-db-provision.test.ts (bash cannot import TS).
LOCK_KEY='repworth_live_db_integration'

# The one owner of the test DB's PostgreSQL major (see header). Pinned against
# REQUIRED_PG_MAJOR in schema-ready.ts and the CI `postgres:<major>` images
# by schema-ready.test.ts.
REQUIRED_PG_MAJOR=17

MIGRATIONS=$(ls supabase/migrations/*.sql | sort)
HEAD_MIGRATION=$(printf '%s\n' "$MIGRATIONS" | tail -1 | xargs basename)

# Hash of the ordered bootstrap + migration contents. ci:rls-audit recomputes
# this from the same files, so a marker from an edited or shorter chain reads
# as not-at-head — recording only the head FILENAME would miss edits.
content_hash() {
  { cat scripts/ci/test-db-bootstrap.sql
    printf '%s\n' "$MIGRATIONS" | while IFS= read -r f; do cat "$f"; done
  } | shasum -a 256 | cut -d' ' -f1
}

print_driver() {
  local hash="$1"
  cat <<SQL
-- Generated by scripts/test-db-setup.sh — one session, lock first, marker last.
SET statement_timeout = '240s';
SELECT pg_advisory_lock(hashtext('${LOCK_KEY}'));
RESET statement_timeout;
DO \$\$ BEGIN IF current_setting('server_version_num')::int < $((REQUIRED_PG_MAJOR * 10000)) THEN RAISE EXCEPTION 'test database runs PostgreSQL %; the required major is ${REQUIRED_PG_MAJOR} (CI and both Supabase projects) — point TEST_DATABASE_POOL_URL at a postgres:${REQUIRED_PG_MAJOR} container (scripts/test-db-setup.sh header)', current_setting('server_version'); END IF; END \$\$;
DROP SCHEMA IF EXISTS test_meta CASCADE;
DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;
\\i scripts/ci/test-db-bootstrap.sql
RESET ALL;
SQL
  printf '%s\n' "$MIGRATIONS" | while IFS= read -r migration; do
    printf '\\i %s\nRESET ALL;\n' "$migration"
  done
  cat <<SQL
CREATE SCHEMA test_meta;
CREATE TABLE test_meta.provision (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  content_hash text NOT NULL,
  head_migration text NOT NULL,
  provisioned_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO test_meta.provision (content_hash, head_migration)
VALUES ('${hash}', '${HEAD_MIGRATION}');
SQL
}

if [ "${1:-}" = "--print-driver" ]; then
  print_driver "$(content_hash)"
  exit 0
fi

DB_URL="${TEST_DATABASE_POOL_URL:-}"
if [ -z "$DB_URL" ] && [ -f .env.local ]; then
  DB_URL=$(sed -nE 's/^[[:space:]]*TEST_DATABASE_POOL_URL[[:space:]]*=[[:space:]]*"?([^"]*)"?[[:space:]]*$/\1/p' .env.local | head -1)
fi

if [ -z "$DB_URL" ]; then
  echo "TEST_DATABASE_POOL_URL is unset (checked the environment and .env.local)." >&2
  echo "See docs/runbooks/e2e-local-setup.md for creating the container." >&2
  exit 1
fi

# Destructive-by-nature DDL: refuse anything that is not a local database.
HOST=$(printf '%s' "$DB_URL" | sed -nE 's#^[a-z+]+://[^@]*@?([^:/?]+).*#\1#p')
case "$HOST" in
  localhost|127.0.0.1|::1) ;;
  *)
    echo "refusing to apply migrations to non-local host '$HOST' — test DB setup is local-only." >&2
    exit 1
    ;;
esac

# ORDER MATTERS inside the driver: the schema recreate drops every grant on
# schema public, and on PG15+ the new schema is created with NO grant to
# PUBLIC. The bootstrap include is what restores USAGE for
# anon/authenticated/service_role. Moving the bootstrap above the reset, or
# dropping the schema after it, silently returns every RLS/permission suite to
# failing locally while passing in CI.
DRIVER=$(mktemp -t test-db-driver.XXXXXX)
trap 'rm -f "$DRIVER"' EXIT
print_driver "$(content_hash)" > "$DRIVER"

echo "→ acquiring the live-DB advisory lock, then resetting schema public on '$HOST' (test database — all data is discarded)"
psql "$DB_URL" -v ON_ERROR_STOP=1 -q -f "$DRIVER"

echo "✔ test database at head (${HEAD_MIGRATION}; test_meta.provision marker written)"
