interface RouteRow { path: string; methods: string[]; gates: string[] }

/** Real declaration emission and standalone-consumer typecheck: no aliases or repo imports. */
export function emitPortableDeclarations(sourceText: string): string {
  const filename = resolve(tmpdir(), 'repworth-admin-api-contract.ts');
  const options: ts.CompilerOptions = {
    strict: true, declaration: true, emitDeclarationOnly: true,
    target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext,
    skipLibCheck: true, types: [],
  };
  const host = ts.createCompilerHost(options);
  const originalRead = host.readFile.bind(host);
  host.readFile = (file) => file === filename ? sourceText : originalRead(file);
  const originalExists = host.fileExists.bind(host);
  host.fileExists = (file) => file === filename || originalExists(file);
  let emitted = '';
  host.writeFile = (file, contents) => { if (file.endsWith('.d.ts')) emitted = contents; };
  const program = ts.createProgram([filename], options, host);
  const errors = ts.getPreEmitDiagnostics(program);
  if (errors.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(errors, {
    getCanonicalFileName: (file) => file, getCurrentDirectory: () => tmpdir(), getNewLine: () => '\n',
  }));
  const result = program.emit();
  if (result.emitSkipped || !emitted) throw new Error('Standalone contract declaration emission failed');
  return `// Generated by pnpm admin-contract:generate. Do not edit.\n${emitted}`;
}

async function listFiles(root: string, prefix = ''): Promise<string[]> {
  let entries;
  try {
    const directory = join(root, prefix);
    if ((await lstat(directory)).isSymbolicLink()) throw new Error(`Contract artifact symlink is unsupported: ${directory}`);
    entries = await readdir(directory, { withFileTypes: true });
  }
  catch (error) {
    if (prefix === '' && (error as NodeJS.ErrnoException).code === 'ENOENT') return [];
    throw error;
  }
  const files: string[] = [];
  for (const entry of entries) {
    if (entry.isSymbolicLink()) throw new Error(`Contract artifact symlink is unsupported: ${join(prefix, entry.name)}`);
    const path = join(prefix, entry.name);
    if (entry.isDirectory()) files.push(...await listFiles(root, path));
    else if (entry.isFile()) files.push(path);
    else throw new Error(`Unsupported contract artifact: ${path}`);
  }
  return files.sort();
}

export async function auditContractFiles(root: string, expected: ReadonlyMap<string, string>): Promise<string[]> {
  const findings: string[] = [];
  const actual = new Set(await listFiles(root));
  for (const [file, contents] of expected) {
    if (!actual.has(file)) { findings.push(`missing artifact ${file}`); continue; }
    const existing = await readFile(join(root, file), 'utf8');
    if (existing !== contents) {
      const left = existing.split('\n'); const right = contents.split('\n');
      const line = right.findIndex((value, index) => value !== left[index]);
      findings.push(`changed artifact ${file}:${line + 1}\n- ${left[line] ?? '(absent)'}\n+ ${right[line] ?? '(absent)'}`);
    }
    actual.delete(file);
  }
  for (const file of actual) findings.push(`stale artifact ${file}`);
  return findings;
}

/** Completeness is independently checked against the committed route table. */
export function checkRouteTable(readme: string, rows: readonly RouteRow[]): string[] {
  const actual = new Map<string, string[]>();
  const findings: string[] = [];
  for (const line of readme.split('\n')) {
    if (!line.startsWith('| `/api/admin')) continue;
    const columns = line.split('|').slice(1, -1).map((value) => value.trim());
    const path = columns[0]?.replace(/`/g, '') ?? '';
    if (actual.has(path)) findings.push(`duplicate route row ${path}`);
    actual.set(path, columns);
  }
  for (const row of rows) {
    const columns = actual.get(row.path);
    if (!columns) { findings.push(`missing route row ${row.path}`); continue; }
    if (columns[1] !== row.methods.join(', ')) findings.push(`methods differ for ${row.path}`);
    if (columns[2] !== row.gates.join('<br>')) findings.push(`gate provenance differs for ${row.path}`);
    actual.delete(row.path);
  }
  for (const path of actual.keys()) findings.push(`stale route row ${path}`);
  return findings;
}

function typeName(path: string, method: string): string {
  return `${path.replace('/api/admin/', '').split(/[^a-zA-Z0-9]+/).filter(Boolean).map((part) => part[0]!.toUpperCase() + part.slice(1)).join('')}${method}Response`;
}

const README_HEADER = `# Admin API contract

Generated from application source. Regenerate with \`pnpm admin-contract:generate\`;
\`pnpm ci:admin-contract\` fails if committed artifacts drift. This detects change,
not whether a change is breaking. No API version is currently assigned.

Use the method-specific response types for JSON wire bodies. Existing service DTO
exports are also included, but a route may enrich or project a service result.
Declarations have no private repository imports. Wire types describe successfully
serialized JSON: invalid dates and non-finite numbers may be null; unknown nested
source payloads stay JSON values and object properties may be omitted. Types do not
promise serialization succeeds for every runtime value. Status unions are an
over-approximation of reachable source branches, not a status/body discriminant.
Status codes are derived from literals, constant maps and domain-error constructor
arguments. An unresolved status expression fails generation. Unexpected framework
failures may also produce non-JSON 5xx.

Request schemas are built-in Zod JSON Schema input projections. Schema metadata
records source provenance, refinements and normalization limitations. Where marked
as approximate, constraints may apply after normalization: do not use these schemas
as complete preflight validators. The API's runtime parser is authoritative.
Bodyless and hand-parsed requests have no invented request schema.

The general error envelope is \`{ error: string }\`; its string is display text,
not a universal machine-code vocabulary. Existing exceptions are retained in the
generated response types: solicitation batch halt returns status-union bodies on
404 and 409. Other metadata beside error is preserved where present.

Proxy branch 4 cookie refusals: 401 \`{error:'Unauthorized'}\`,
403 \`{error:'Forbidden'}\`, and 403 \`{error:<aal gate value>}\`.
The MFA vocabulary includes \`mfa_required\` and \`mfa_check_failed\`.
On \`mfa_required\`, the Admin app completes its own MFA challenge and retries
with the resulting AAL2 bearer. An Authorization header selects bearer mode;
the canonical route gate verifies it. CORS may refuse an origin with
403 \`{error:'origin'}\` before the route. Impersonation remains in the legacy app
with its cookie/CSRF behavior; listing those routes here does not authorize a port.

| Route | Methods | Canonical gates | Request schema or absence | Wire response types | Source status codes |
| --- | --- | --- | --- | --- | --- |
`;

export async function generateAdminContract(root: string): Promise<{ files: Map<string, string>; rows: RouteRow[] }> {
  const configPath = join(root, 'tsconfig.json');
  const config = ts.readConfigFile(configPath, ts.sys.readFile);
  if (config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'));
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
  if (parsed.errors.length) throw new Error(parsed.errors.map((error) => ts.flattenDiagnosticMessageText(error.messageText, '\n')).join('\n'));
  const routes: string[] = [];
  await collectRouteFiles(join(root, 'src/app/api/admin'), root, routes);
  if (!routes.length) throw new Error('No Admin API route files found');
  const barrelPath = join(root, 'src/lib/admin/api-contract.ts');
  const program = ts.createProgram([...routes.map((file) => join(root, file)), barrelPath], parsed.options);
  const checker = program.getTypeChecker();
  const barrel = program.getSourceFile(barrelPath);
  if (!barrel) throw new Error('Admin DTO barrel is missing');
  const symbol = checker.getSymbolAtLocation(barrel);
  if (!symbol) throw new Error('Admin DTO barrel is not a module');
  const declarations = [JSON_VALUE_DECLARATION];
  for (const exported of checker.getExportsOfModule(symbol).sort((a, b) => a.name.localeCompare(b.name))) {
    const target = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
    const declaration = target.declarations?.[0];
    if (!declaration || (!ts.isInterfaceDeclaration(declaration) && !ts.isTypeAliasDeclaration(declaration))) throw new Error(`DTO export ${exported.name} must reference an existing type`);
    declarations.push(`export type ${exported.name} = ${renderJsonType(checker, checker.getDeclaredTypeOfSymbol(target), declaration, false)};`);
  }
  const files = new Map<string, string>();
  const rows: RouteRow[] = [];
  const lines: string[] = [];
  for (const file of routes.sort()) {
    const source = program.getSourceFile(join(root, file));
    if (!source) throw new Error(`Compiler could not read ${file}`);
    const handlers = describeRouteHandlers(file, source.text);
    if (!handlers.length) throw new Error(`Admin route has no exported methods: ${file}`);
    const path = `/${file.replace(/^src\/app\//, '').replace(/\/route\.[^.]+$/, '')}`;
    const row = { path, methods: handlers.map((handler) => handler.method), gates: handlers.map((handler) => `${handler.method}: ${handler.gates.join(', ')}`) };
    rows.push(row);
    const requests: string[] = []; const names: string[] = []; const statuses: string[] = [];
    for (const handler of handlers) {
      const name = typeName(path, handler.method);
      const responses = describeResponses(program, source, handler.method);
      const bodies = [...new Set(responses.map((response) => response.body))].sort();
      declarations.push(`/** ${handler.method} ${path}; derived from actual JSON response expressions. */\nexport type ${name} = ${bodies.join(' | ')};`);
      names.push(`\`${name}\``);
      statuses.push(`${handler.method}: ${[...new Set(responses.map((response) => response.status))].sort().join(', ').replace(/\|/g, '&#124;')}`);
      const request = generateRequestSchemas(program, source, handler.method);
      if (!request.schemas.length) requests.push(`${handler.method}: ${request.body === 'none' ? 'no request body' : request.body}`);
      for (const schema of request.schemas) {
        const schemaFile = `schemas/${name.replace(/Response$/, '')}-${schema.location}-${schema.name}.json`;
        const content = JSON.stringify({ ...schema.schema, 'x-repworth-source': schema.source.replaceAll(`${root}/`, ''), 'x-repworth-approximation': schema.approximation, 'x-repworth-limitations': schema.limitations }, null, 2) + '\n';
        if (files.has(schemaFile)) throw new Error(`Duplicate schema output ${schemaFile}`);
        files.set(schemaFile, content);
        requests.push(`${handler.method} ${schema.location}: [${schema.name}](${schemaFile})${schema.approximation ? ' (approximate)' : ''}`);
      }
    }
    lines.push(`| \`${path}\` | ${row.methods.join(', ')} | ${row.gates.join('<br>')} | ${requests.join('<br>')} | ${names.join('<br>')} | ${statuses.join('<br>')} |`);
  }
  files.set('admin-api.d.ts', emitPortableDeclarations(declarations.join('\n\n')));
  files.set('README.md', README_HEADER + lines.join('\n') + '\n');
  return { files, rows };
}

async function writeArtifacts(root: string, files: ReadonlyMap<string, string>): Promise<void> {
  for (const [file, contents] of files) { await mkdir(dirname(join(root, file)), { recursive: true }); await writeFile(join(root, file), contents); }
}

async function main(): Promise<void> {
  const root = process.cwd();
  const destination = join(root, 'docs/admin-api');
  // Check the bounded output ancestry before any artifact read, cleanup or write.
  for (const directory of [join(root, 'docs'), destination]) {
    try {
      const stat = await lstat(directory);
      if (stat.isSymbolicLink()) throw new Error(`Contract artifact symlink is unsupported: ${directory}`);
      if (!stat.isDirectory()) throw new Error(`Contract artifact directory is required: ${directory}`);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    }
  }
  const generated = await generateAdminContract(root);
  if (process.argv.includes('--write')) {
    // Only generated files inside the contract directory are removed; caller chose regeneration.
    for (const file of await listFiles(destination)) if (!generated.files.has(file)) await rm(join(destination, file));
    await writeArtifacts(destination, generated.files);
    console.log(`Generated ${generated.files.size} artifacts for ${generated.rows.length} Admin API routes.`);
    return;
  }
  const temporary = await mkdtemp(join(tmpdir(), 'repworth-admin-contract-'));
  try {
    await writeArtifacts(temporary, generated.files);
    const findings = await auditContractFiles(destination, generated.files);
    const readme = await readFile(join(destination, 'README.md'), 'utf8').catch((error: NodeJS.ErrnoException) => { if (error.code === 'ENOENT') return ''; throw error; });
    findings.push(...checkRouteTable(readme, generated.rows));
    if (findings.length) throw new Error(`${findings.join('\n')}\nRun pnpm admin-contract:generate and commit the resulting artifacts.`);
    console.log(`PASS: ${generated.rows.length} Admin API routes; ${generated.files.size} byte-identical artifacts; canonical gate provenance verified.`);
  } finally { await rm(temporary, { recursive: true, force: true }); }
}

