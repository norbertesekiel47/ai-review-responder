import { describe, expect, it } from 'vitest';
import { legalDocs } from '../content';

describe('legal content', () => {
  it('publishes material Terms sections on the route-backed typed document', () => {
    const headings = legalDocs.terms.sections.map((section) => section.heading);

    expect(headings).toEqual(expect.arrayContaining([
      'Notifications',
      'Disclaimer of Warranties',
      'Limitation of Liability',
      'Termination',
      'Governing Law',
    ]));
  });

  it('publishes detailed Privacy data classes and live sub-processors', () => {
    const dataSection = legalDocs.privacy.sections.find(
      (section) => section.heading === 'Data We Process',
    );
    const subProcessorSection = legalDocs.privacy.sections.find(
      (section) => section.heading === 'Sub-processors',
    );
    expect(dataSection).toBeDefined();
    expect(subProcessorSection).toBeDefined();

    const vendors = subProcessorSection?.table?.rows.map((row) => row[0]) ?? [];

    expect(dataSection?.bullets).toEqual(expect.arrayContaining([
      expect.stringContaining('Account data:'),
      expect.stringContaining('Review data:'),
      expect.stringContaining('Reliability and service metadata:'),
    ]));
    expect(vendors).toEqual(expect.arrayContaining([
      'SerpAPI',
      'Google Maps Platform',
    ]));
    for (const excluded of ['PostHog', 'Help Scout', 'Cloudflare', 'Loops', 'Customer.io']) {
      expect(vendors).not.toContain(excluded);
    }
  });
});

describe('legal content — launch P0 #11 removals', () => {
  const AI_MICROCOPY = 'Draft generated by AI. Review carefully before approving.';

  it('does not expose a DPA placeholder document', () => {
    expect(Object.keys(legalDocs)).not.toContain('dpa');
  });

  it('does not paste the UI microcopy into any legal document body', () => {
    for (const doc of Object.values(legalDocs)) {
      for (const section of doc.sections) {
        expect(section.body).not.toContain(AI_MICROCOPY);
      }
    }
  });

  it('keeps the substantive AI disclosure but drops the misplaced microcopy in Terms', () => {
    const aiContent = legalDocs.terms.sections.find(
      (section) => section.heading === 'AI-Generated Content',
    );

    expect(aiContent).toBeDefined();
    expect(aiContent?.body).not.toContain(AI_MICROCOPY);
    expect(aiContent?.body.join(' ')).toContain('Response drafts are suggestions only');
  });

  it('keeps the substantive AI disclosure but drops the misplaced microcopy in Privacy', () => {
    const howWeUse = legalDocs.privacy.sections.find(
      (section) => section.heading === 'How We Use Data',
    );
    const aiSection = legalDocs.privacy.sections.find(
      (section) => section.heading === 'AI Draft Generation',
    );

    expect(howWeUse).toBeDefined();
    expect(howWeUse?.body).not.toContain(AI_MICROCOPY);
    expect(howWeUse?.bullets?.length).toBeGreaterThan(0);
    expect(aiSection).toBeDefined();
    expect(aiSection?.body.join(' ')).toContain('OpenAI or Anthropic');
  });

  it('keeps the owner-responsibility prose but drops the misplaced microcopy in AUP', () => {
    const responsibility = legalDocs.aup.sections.find(
      (section) => section.heading === 'Review and Approval Responsibility',
    );

    expect(responsibility).toBeDefined();
    expect(responsibility?.body).not.toContain(AI_MICROCOPY);
    expect(responsibility?.body.join(' ')).toContain(
      'Owners are responsible for reviewing each draft before approval',
    );
  });
});

describe('legal content — owner offboarding launch gate (PR7 Task 7.3)', () => {
  it('discloses the non-refundable forfeiture for mid-cycle delete_data', () => {
    const billing = legalDocs.terms.sections.find(
      (section) => section.heading === 'Subscription and Billing',
    );
    expect(billing).toBeDefined();

    const billingText = billing?.body.join(' ') ?? '';
    expect(billingText).toContain('immediate account deletion');
    expect(billingText).toContain('forfeit the remaining paid time');
    expect(billingText).toContain('non-refundable');
    expect(billingText).toContain('does not provide a self-serve data export');
  });

  it('makes the delete-or-anonymize promise without claiming absolute deletion', () => {
    const termination = legalDocs.terms.sections.find(
      (section) => section.heading === 'Termination',
    );
    expect(termination).toBeDefined();

    const terminationText = termination?.body.join(' ') ?? '';
    expect(terminationText).toContain('deletes or anonymizes');
    expect(terminationText).toContain(
      'retaining limited billing, security, and compliance records',
    );
    expect(terminationText).toContain('does not promise absolute deletion');
  });
});
