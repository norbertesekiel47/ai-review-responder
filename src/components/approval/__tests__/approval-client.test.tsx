// @vitest-environment jsdom

import { render, screen, fireEvent } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { afterEach, describe, expect, it, vi } from 'vitest';
import ApprovalClient from '../approval-client';
// Test files are exempt from the app/** import ban — import the server's
// authoritative cap to guard against the client mirror drifting from it.
import { MAX_EDIT_LENGTH } from '@/app/api/approve/[token]/edit/validation';

// ApprovalClient uses useQuery; in production it inherits the QueryClient from
// the root layout's RootProviders. Tests render it in isolation, so each render
// must supply its own fresh client.
function renderClient(token: string) {
  const queryClient = new QueryClient();
  return render(
    <QueryClientProvider client={queryClient}>
      <ApprovalClient token={token} />
    </QueryClientProvider>,
  );
}

const REVIEW_DATA = {
  review: {
    reviewerName: 'Alex',
    starRating: 5,
    reviewText: 'Great visit.',
    reviewDate: '2026-05-25T12:00:00Z',
  },
  response: {
    responseText: 'Thanks for visiting.',
    version: 2,
    status: 'pending_approval',
  },
  businessName: 'RepWorth Demo',
  locationLabel: 'Main Street',
  isArchived: false,
  expiresAt: new Date(Date.now() + 3_600_000).toISOString(),
};

// fetch mock: GET token -> review data, POST /session -> ok,
// POST /<action> -> the provided action response.
function stubFetch(actionResponse?: { ok: boolean; status: number; body: unknown }) {
  const fetchMock = vi.fn(async (input: RequestInfo | URL, _init?: RequestInit) => {
    const url = String(input);
    if (url.endsWith('/session')) {
      return { ok: true, status: 200, json: async () => ({}) } as Response;
    }
    if (url.endsWith('/approve') || url.endsWith('/edit') || url.endsWith('/regenerate')) {
      const r = actionResponse ?? { ok: true, status: 200, body: {} };
      return { ok: r.ok, status: r.status, json: async () => r.body } as Response;
    }
    return { ok: true, status: 200, json: async () => REVIEW_DATA } as Response;
  });
  vi.stubGlobal('fetch', fetchMock);
  return fetchMock;
}

describe('ApprovalClient', () => {
  afterEach(() => {
    vi.unstubAllGlobals();
    vi.restoreAllMocks();
  });

  it('discloses that the draft was generated by AI before approval actions', async () => {
    stubFetch();
    renderClient('raw-token');

    expect(
      await screen.findByText(
        'Draft generated by AI. Review carefully before approving.',
      ),
    ).toBeInTheDocument();
    expect(
      screen.getByRole('button', { name: 'Approve & post to Google' }),
    ).toBeInTheDocument();
  });

  it('reassures the recipient that nothing posts unless they approve', async () => {
    stubFetch();
    renderClient('raw-token');

    expect(
      await screen.findByText(/nothing posts unless you approve/i),
    ).toBeInTheDocument();
  });

  it('requires a second confirming tap before posting an approval to Google', async () => {
    const fetchMock = stubFetch({
      ok: true,
      status: 200,
      body: { success: true, message: 'Approved — posting to Google has started.' },
    });
    renderClient('raw-token');

    // First tap arms the confirm step — it must NOT post yet.
    fireEvent.click(
      await screen.findByRole('button', { name: 'Approve & post to Google' }),
    );
    const postCallsAfterArm = fetchMock.mock.calls.filter((c) =>
      String(c[0]).endsWith('/approve'),
    ).length;
    expect(postCallsAfterArm).toBe(0);

    // The morphed confirm button is now visible.
    const confirm = await screen.findByRole('button', {
      name: 'Tap again to post to Google',
    });

    // Second tap actually posts.
    fireEvent.click(confirm);
    expect(await screen.findByText('Response approved!')).toBeInTheDocument();
    expect(
      screen.getByText('Approved — posting to Google has started.'),
    ).toBeInTheDocument();
  });

  it('lets the recipient back out of the confirm step without posting', async () => {
    const fetchMock = stubFetch();
    renderClient('raw-token');

    fireEvent.click(
      await screen.findByRole('button', { name: 'Approve & post to Google' }),
    );
    // Arming surfaces a Cancel affordance; clicking it disarms.
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }));

    // Back to the resting primary label, and nothing was posted.
    expect(
      await screen.findByRole('button', { name: 'Approve & post to Google' }),
    ).toBeInTheDocument();
    expect(
      fetchMock.mock.calls.filter((c) => String(c[0]).endsWith('/approve')).length,
    ).toBe(0);
  });

  it('shows a friendly expiry when under an hour remains (never "0 hours")', async () => {
    const fetchMock = vi.fn(async (input: RequestInfo | URL) => {
      const url = String(input);
      if (url.endsWith('/session')) {
        return { ok: true, status: 200, json: async () => ({}) } as Response;
      }
      return {
        ok: true,
        status: 200,
        json: async () => ({
          ...REVIEW_DATA,
          // 10 minutes left — the old Math.round logic rendered "0 hours".
          expiresAt: new Date(Date.now() + 10 * 60_000).toISOString(),
        }),
      } as Response;
    });
    vi.stubGlobal('fetch', fetchMock);
    renderClient('raw-token');

    expect(await screen.findByText(/expires in 10 minutes/i)).toBeInTheDocument();
    expect(screen.queryByText(/0 hours/i)).not.toBeInTheDocument();
  });

  it('exposes the star rating to screen readers', async () => {
    stubFetch();
    renderClient('raw-token');

    expect(await screen.findByText('5 out of 5 stars')).toBeInTheDocument();
  });

  it('labels the edit textarea', async () => {
    stubFetch();
    renderClient('raw-token');

    fireEvent.click(await screen.findByRole('button', { name: 'Edit' }));
    expect(screen.getByLabelText('Edit your response')).toBeInTheDocument();
  });

  it('shows an action-aware success state with a demoted dashboard link after approving', async () => {
    stubFetch({
      ok: true,
      status: 200,
      body: { success: true, message: 'Approved — posting to Google has started.' },
    });
    renderClient('raw-token');

    fireEvent.click(
      await screen.findByRole('button', { name: 'Approve & post to Google' }),
    );
    fireEvent.click(
      await screen.findByRole('button', { name: 'Tap again to post to Google' }),
    );

    expect(await screen.findByText('Response approved!')).toBeInTheDocument();
    expect(
      screen.getByText('Approved — posting to Google has started.'),
    ).toBeInTheDocument();
    // Primary affordance is a confirmation message, not a dashboard link.
    expect(
      screen.getByText(/you can safely close this page/i),
    ).toBeInTheDocument();
    // Dashboard is demoted to a quiet secondary link.
    expect(
      screen.getByRole('link', { name: /dashboard/i }),
    ).toHaveAttribute('href', '/dashboard');
  });

  it('shows the regenerate heading after requesting a new draft', async () => {
    stubFetch({
      ok: true,
      status: 200,
      body: { success: true, message: 'Generating a new response - check your email in a few minutes.' },
    });
    renderClient('raw-token');

    fireEvent.click(await screen.findByRole('button', { name: 'Regenerate' }));

    expect(await screen.findByText('New draft on the way')).toBeInTheDocument();
    expect(
      screen.getByText('Generating a new response - check your email in a few minutes.'),
    ).toBeInTheDocument();
  });

  it('still shows the success view when the API returns an empty message', async () => {
    stubFetch({ ok: true, status: 200, body: { success: true, message: '' } });
    renderClient('raw-token');

    fireEvent.click(
      await screen.findByRole('button', { name: 'Approve & post to Google' }),
    );
    fireEvent.click(
      await screen.findByRole('button', { name: 'Tap again to post to Google' }),
    );

    // An empty message must not suppress the success state (the view gates on
    // successMessage truthiness); it falls back to the default copy.
    expect(await screen.findByText('Response approved!')).toBeInTheDocument();
    expect(
      screen.getByText('Your request has been processed.'),
    ).toBeInTheDocument();
  });

  it('maps a failed load to friendly copy with support recovery', async () => {
    const fetchMock = vi.fn(async () =>
      ({ ok: false, status: 410, json: async () => ({ error: 'gone' }) }) as Response,
    );
    vi.stubGlobal('fetch', fetchMock);
    renderClient('raw-token');

    // 410 maps to friendly used/expired copy — never the raw server string.
    expect(
      await screen.findByText(/already been used or has expired/i),
    ).toBeInTheDocument();
    expect(screen.queryByText('gone')).not.toBeInTheDocument();
    // Support is the primary recovery; dashboard is a quiet secondary link.
    expect(
      screen.getByRole('link', { name: /contact support/i }),
    ).toHaveAttribute('href', '/help/contact');
    expect(
      screen.getByRole('link', { name: /dashboard/i }),
    ).toHaveAttribute('href', '/dashboard');
  });

  it('keeps the review visible with a friendly inline alert when an action fails', async () => {
    stubFetch({
      ok: false,
      status: 409,
      body: { error: 'This response has already been approved.' },
    });
    renderClient('raw-token');

    fireEvent.click(
      await screen.findByRole('button', { name: 'Approve & post to Google' }),
    );
    fireEvent.click(
      await screen.findByRole('button', { name: 'Tap again to post to Google' }),
    );

    // 409 maps to friendly "draft changed, refresh" copy — never the raw server string.
    expect(await screen.findByText(/this draft has changed/i)).toBeInTheDocument();
    expect(
      screen.queryByText('This response has already been approved.'),
    ).not.toBeInTheDocument();
    // ...but the review + actions stay on screen (not replaced by the full error island).
    expect(screen.getByText(/Alex/)).toBeInTheDocument();
    expect(
      screen.getByRole('button', { name: 'Approve & post to Google' }),
    ).toBeInTheDocument();
  });

  it('maps a 5xx action failure to friendly copy (never "HTTP 500")', async () => {
    stubFetch({
      ok: false,
      status: 500,
      body: { error: 'Internal Server Error' },
    });
    renderClient('raw-token');

    fireEvent.click(
      await screen.findByRole('button', { name: 'Approve & post to Google' }),
    );
    fireEvent.click(
      await screen.findByRole('button', { name: 'Tap again to post to Google' }),
    );

    expect(
      await screen.findByText(/something went wrong on our end/i),
    ).toBeInTheDocument();
    expect(screen.queryByText(/HTTP 500/)).not.toBeInTheDocument();
    expect(screen.queryByText('Internal Server Error')).not.toBeInTheDocument();
  });

  it('shows a neutral Archived badge for archived locations', async () => {
    const fetchMock = vi.fn(async (input: RequestInfo | URL) => {
      const url = String(input);
      if (url.endsWith('/session')) {
        return { ok: true, status: 200, json: async () => ({}) } as Response;
      }
      return {
        ok: true,
        status: 200,
        json: async () => ({ ...REVIEW_DATA, isArchived: true }),
      } as Response;
    });
    vi.stubGlobal('fetch', fetchMock);
    renderClient('raw-token');

    expect(await screen.findByText('Archived')).toBeInTheDocument();
  });

  it('saves an edited response after a confirming second tap', async () => {
    const fetchMock = stubFetch({
      ok: true,
      status: 200,
      body: { success: true, message: 'Approved with your edits — posting to Google has started.' },
    });
    renderClient('raw-token');

    fireEvent.click(await screen.findByRole('button', { name: 'Edit' }));
    fireEvent.change(screen.getByLabelText('Edit your response'), {
      target: { value: 'Thank you so much, Alex!' },
    });

    // First tap arms; nothing posts yet.
    fireEvent.click(screen.getByRole('button', { name: 'Save & post to Google' }));
    expect(
      fetchMock.mock.calls.filter((c) => String(c[0]).endsWith('/edit')).length,
    ).toBe(0);

    // Second tap posts the snapshotted edited text.
    fireEvent.click(
      await screen.findByRole('button', { name: 'Tap again to post to Google' }),
    );

    expect(await screen.findByText('Response approved!')).toBeInTheDocument();
    expect(
      screen.getByText('Approved with your edits — posting to Google has started.'),
    ).toBeInTheDocument();

    const editCall = fetchMock.mock.calls.find((c) => String(c[0]).endsWith('/edit'));
    expect(editCall).toBeDefined();
    expect(JSON.parse(String(editCall?.[1]?.body))).toEqual({
      editedText: 'Thank you so much, Alex!',
    });
  });

  describe('scheduled auto-post state (WS4 veto surface)', () => {
    function scheduledData(overrides?: Record<string, unknown>) {
      return {
        ...REVIEW_DATA,
        response: {
          ...REVIEW_DATA.response,
          status: 'approved',
          approvalMethod: 'auto_policy',
          autoPostScheduledAt: new Date(Date.now() + 30 * 60_000).toISOString(),
          ...overrides,
        },
      };
    }

    function stubScheduledFetch(
      data: unknown,
      vetoResponse?: { ok: boolean; status: number; body: unknown },
    ) {
      const fetchMock = vi.fn(async (input: RequestInfo | URL, _init?: RequestInit) => {
        const url = String(input);
        if (url.endsWith('/session')) {
          return { ok: true, status: 200, json: async () => ({}) } as Response;
        }
        if (url.endsWith('/veto')) {
          const r = vetoResponse ?? { ok: true, status: 200, body: { result: 'cancelled' } };
          return { ok: r.ok, status: r.status, json: async () => r.body } as Response;
        }
        return { ok: true, status: 200, json: async () => data } as Response;
      });
      vi.stubGlobal('fetch', fetchMock);
      return fetchMock;
    }

    it('renders a read-only draft with the posting time and a single Cancel auto-post action', async () => {
      stubScheduledFetch(scheduledData());
      renderClient('raw-token');

      // Absolute-UTC + relative phrasing, mirroring the notice copy owner.
      expect(
        await screen.findByText(/posting automatically at \d{2}:\d{2} utc \(in about \d+ minutes?\)/i),
      ).toBeInTheDocument();
      expect(
        screen.getByRole('button', { name: 'Cancel auto-post' }),
      ).toBeInTheDocument();
      // The draft is read-only: no approve/edit/regenerate actions.
      expect(
        screen.queryByRole('button', { name: 'Approve & post to Google' }),
      ).not.toBeInTheDocument();
      expect(screen.queryByRole('button', { name: 'Edit' })).not.toBeInTheDocument();
      // The review + draft stay visible for context.
      expect(screen.getByText(/Alex/)).toBeInTheDocument();
      expect(screen.getByText('Thanks for visiting.')).toBeInTheDocument();
    });

    it('POSTs the veto route on cancel and shows the queue-returned confirmation', async () => {
      const fetchMock = stubScheduledFetch(scheduledData(), {
        ok: true,
        status: 200,
        body: { result: 'cancelled' },
      });
      renderClient('raw-token');

      fireEvent.click(await screen.findByRole('button', { name: 'Cancel auto-post' }));

      expect(await screen.findByText('Auto-post cancelled')).toBeInTheDocument();
      expect(
        screen.getByText(/back in your approval queue.*fresh approval link/i),
      ).toBeInTheDocument();
      expect(screen.getByRole('link', { name: /dashboard/i })).toHaveAttribute(
        'href',
        '/dashboard',
      );
      const vetoCall = fetchMock.mock.calls.find((c) => String(c[0]).endsWith('/veto'));
      expect(vetoCall).toBeDefined();
      expect(vetoCall?.[1]).toMatchObject({ method: 'POST' });
    });

    it('treats already_cancelled like cancelled (double-tap safe)', async () => {
      stubScheduledFetch(scheduledData(), {
        ok: true,
        status: 200,
        body: { result: 'already_cancelled' },
      });
      renderClient('raw-token');

      fireEvent.click(await screen.findByRole('button', { name: 'Cancel auto-post' }));

      expect(await screen.findByText('Auto-post cancelled')).toBeInTheDocument();
    });

    it('shows the non-committal window-closed state on a too_late 409', async () => {
      stubScheduledFetch(scheduledData(), {
        ok: false,
        status: 409,
        body: { result: 'too_late' },
      });
      renderClient('raw-token');

      fireEvent.click(await screen.findByRole('button', { name: 'Cancel auto-post' }));

      expect(
        await screen.findByText('This link can no longer cancel the post'),
      ).toBeInTheDocument();
      // Non-committal: covers both "posted/posting" and "returned to the
      // queue by another path" without asserting either.
      expect(screen.getByText(/check your dashboard for the current status/i)).toBeInTheDocument();
      expect(
        screen.queryByRole('button', { name: 'Cancel auto-post' }),
      ).not.toBeInTheDocument();
    });

    it('renders the window-closed state directly when the scheduled time already passed', async () => {
      stubScheduledFetch(
        scheduledData({
          autoPostScheduledAt: new Date(Date.now() - 60_000).toISOString(),
        }),
      );
      renderClient('raw-token');

      expect(
        await screen.findByText('This link can no longer cancel the post'),
      ).toBeInTheDocument();
      expect(
        screen.queryByRole('button', { name: 'Cancel auto-post' }),
      ).not.toBeInTheDocument();
    });

    it('keeps a generic action failure inline with the cancel still available', async () => {
      stubScheduledFetch(scheduledData(), {
        ok: false,
        status: 500,
        body: { error: 'Internal Server Error' },
      });
      renderClient('raw-token');

      fireEvent.click(await screen.findByRole('button', { name: 'Cancel auto-post' }));

      expect(
        await screen.findByText(/something went wrong on our end/i),
      ).toBeInTheDocument();
      expect(
        screen.getByRole('button', { name: 'Cancel auto-post' }),
      ).toBeInTheDocument();
    });
  });

  it('shows a terminal already-posted state instead of actionable approve UI', async () => {
    const fetchMock = vi.fn(async (input: RequestInfo | URL) => {
      const url = String(input);
      if (url.endsWith('/session')) {
        return { ok: true, status: 200, json: async () => ({}) } as Response;
      }
      return {
        ok: true,
        status: 200,
        json: async () => ({
          ...REVIEW_DATA,
          response: { ...REVIEW_DATA.response, status: 'posted' },
        }),
      } as Response;
    });
    vi.stubGlobal('fetch', fetchMock);
    renderClient('raw-token');

    expect(
      await screen.findByText('This reply has already been posted'),
    ).toBeInTheDocument();
    expect(
      screen.queryByRole('button', { name: 'Approve & post to Google' }),
    ).not.toBeInTheDocument();
    expect(screen.getByRole('link', { name: /dashboard/i })).toHaveAttribute(
      'href',
      '/dashboard',
    );
  });

  it('enforces a maxLength and shows a character counter on the edit textarea', async () => {
    stubFetch();
    renderClient('raw-token');

    fireEvent.click(await screen.findByRole('button', { name: 'Edit' }));
    const textarea = screen.getByLabelText('Edit your response') as HTMLTextAreaElement;
    // The client maxLength must match the server's authoritative cap — this
    // assertion fails if the restated client mirror ever drifts from it.
    expect(textarea.maxLength).toBe(MAX_EDIT_LENGTH);
    // Counter reflects the seeded draft length (default REVIEW_DATA response).
    expect(
      screen.getByText(new RegExp(`/ ${MAX_EDIT_LENGTH}$`)),
    ).toBeInTheDocument();
  });
});
