// InlineGeneratePanel — the whole **On-demand generation** affordance for one
// never-replied row of the Reviews list (#678, spec §6.3a S7).
//
// It owns the `Generate` button AND the in-row expansion the button opens, so
// `useInlineGenerate` is mounted only for the two Action slots that can reach
// it (`generate` / `generating`). A card that renders the hook unconditionally
// would start a poller on every answered row.
//
// Deliberately NOT the two-pane `EditReplyDrawer`: that surface exists to make
// an owner compare their LIVE Google reply against a replacement before
// overwriting it (§6.4). A never-replied review has nothing live, so the left
// pane would be empty and the comparison would overstate the risk of an action
// that only adds a first reply.
//
// Publish goes through `POST /api/dashboard/reviews/:id/approve` (and `/edit`
// for the edited variant) — the same door the Needs Action queue uses, not
// `past-replies/publish`, which is the DELETE-then-POST replace path (#669
// reuse audit).

'use client';

import { Icon } from '@/components/dashboard/shell/Icon';
import { useInlineGenerate } from '@/components/dashboard/reviews/useInlineGenerate';

const MAX_EDIT_LENGTH = 2000;

export function InlineGeneratePanel({
  reviewId,
  resumeGenerating,
}: {
  reviewId: string;
  /** Server-rendered `row_action === 'generating'` — resume the poll on mount. */
  resumeGenerating: boolean;
}) {
  const { state, actions } = useInlineGenerate({ reviewId, resumeGenerating });

  switch (state.kind) {
    case 'idle':
      return (
        <div className="pr-gen-row">
          <button type="button" className="pr-generate-btn" onClick={() => void actions.start()}>
            <Icon name="sparkle" size={12} aria-hidden="true" />
            Generate
          </button>
        </div>
      );

    case 'starting':
    case 'generating':
      return (
        <div className="pr-gen-row">
          <span className="pr-gen-status" role="status">
            <span className="pr-gen-dot" aria-hidden="true" />
            Generating…
          </span>
        </div>
      );

    case 'ready':
      return (
        <div className="pr-gen-panel">
          <p className="pr-gen-draft">{state.text}</p>
          <p className="pr-gen-disclosure">
            Draft generated by AI. Review carefully before approving.
          </p>
          <div className="pr-gen-actions">
            <button
              type="button"
              className="pr-gen-primary"
              onClick={() => void actions.approve()}
            >
              Approve &amp; post
            </button>
            <button type="button" className="pr-edit-btn" onClick={actions.startEdit}>
              <Icon name="edit" size={12} aria-hidden="true" />
              Edit
            </button>
          </div>
        </div>
      );

    case 'editing':
      return (
        <div className="pr-gen-panel">
          <textarea
            className="pr-gen-textarea"
            aria-label="Edit the draft reply"
            value={state.text}
            maxLength={MAX_EDIT_LENGTH}
            rows={5}
            onChange={(event) => actions.changeEditText(event.target.value)}
          />
          <div className="pr-gen-actions">
            <button
              type="button"
              className="pr-gen-primary"
              disabled={state.text.trim().length === 0}
              onClick={() => void actions.saveEdit(state.text)}
            >
              Save &amp; post
            </button>
            <button type="button" className="pr-edit-btn" onClick={actions.cancelEdit}>
              Cancel
            </button>
          </div>
        </div>
      );

    case 'publishing':
      return (
        <div className="pr-gen-row">
          <span className="pr-gen-status" role="status">
            <span className="pr-gen-dot" aria-hidden="true" />
            Posting…
          </span>
        </div>
      );

    case 'posted':
      return (
        <div className="pr-gen-row">
          <span className="pr-gen-done" role="status">
            <Icon name="check" size={12} aria-hidden="true" />
            {state.message}
          </span>
        </div>
      );

    case 'error':
      return (
        <div className="pr-gen-panel">
          <p className="pr-gen-error" role="alert">
            {state.message}
          </p>
          <div className="pr-gen-actions">
            <button type="button" className="pr-edit-btn" onClick={actions.reset}>
              Try again
            </button>
          </div>
        </div>
      );

    default: {
      // Exhaustiveness: a new InlineGenerateState member must be rendered here
      // rather than silently falling through to a blank row.
      const unreachable: never = state;
      return unreachable;
    }
  }
}
