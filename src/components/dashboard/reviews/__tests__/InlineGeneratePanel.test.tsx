// @vitest-environment jsdom
//
// src/components/dashboard/reviews/__tests__/InlineGeneratePanel.test.tsx
//
// The rendered half of the **On-demand generation** affordance (#678). The panel
// is a pure switch over `InlineGenerateState`, but it is driven here through the
// REAL `useInlineGenerate` and a mocked fetch rather than a stubbed hook — the
// wiring (which button calls which action, what the disabled rule is) is the
// part worth pinning, and stubbing the hook would assert only the switch.
//
// `past-reply-card-states.test.tsx` already pins the `generate` row's Generate
// button as seen from PastReplyCard. These titles cover the states BEYOND that
// first click, which nothing reached before.

import { act, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { InlineGeneratePanel } from '@/components/dashboard/reviews/InlineGeneratePanel';

const REVIEW_ID = 'review-1';
const POLL_INTERVAL_MS = 1500;

function jsonResponse(body: unknown, init: { ok?: boolean; status?: number } = {}) {
  const ok = init.ok ?? true;
  const status = init.status ?? (ok ? 200 : 400);
  return { ok, status, json: async () => body } as unknown as Response;
}

let fetchMock: ReturnType<typeof vi.fn>;

beforeEach(() => {
  fetchMock = vi.fn();
  vi.stubGlobal('fetch', fetchMock);
});

afterEach(() => {
  vi.unstubAllGlobals();
  vi.useRealTimers();
});

async function advanceOnePoll() {
  await act(async () => {
    await vi.advanceTimersByTimeAsync(POLL_INTERVAL_MS);
  });
}

/** Click Generate and poll once to a ready draft — the entry point for the rest. */
async function renderReadyDraft(text = 'Thanks for the kind words!') {
  vi.useFakeTimers();
  fetchMock
    .mockResolvedValueOnce(jsonResponse({ outbox_id: 'ob-1', version: 1 }))
    .mockResolvedValueOnce(
      jsonResponse({ status: 'ready', response_id: 'resp-1', response_text: text }),
    );
  const view = render(<InlineGeneratePanel reviewId={REVIEW_ID} resumeGenerating={false} />);
  await act(async () => {
    fireEvent.click(screen.getByRole('button', { name: /^generate$/i }));
  });
  await advanceOnePoll();
  return view;
}

describe('InlineGeneratePanel', () => {
  it('InlineGeneratePanel renders only the Generate button when idle', () => {
    render(<InlineGeneratePanel reviewId={REVIEW_ID} resumeGenerating={false} />);

    expect(screen.getByRole('button', { name: /^generate$/i })).toBeInTheDocument();
    expect(screen.queryByRole('status')).not.toBeInTheDocument();
    expect(fetchMock).not.toHaveBeenCalled();
  });

  it('InlineGeneratePanel shows Generating… from the click until the draft settles', async () => {
    vi.useFakeTimers();
    let resolvePost!: (r: Response) => void;
    fetchMock.mockReturnValueOnce(
      new Promise<Response>((res) => {
        resolvePost = res;
      }),
    );
    render(<InlineGeneratePanel reviewId={REVIEW_ID} resumeGenerating={false} />);

    // 'starting' and 'generating' share one rendering — the owner must not see
    // the button flicker back while the POST is in flight.
    await act(async () => {
      fireEvent.click(screen.getByRole('button', { name: /^generate$/i }));
    });
    expect(screen.getByRole('status')).toHaveTextContent(/generating/i);
    expect(screen.queryByRole('button', { name: /^generate$/i })).not.toBeInTheDocument();

    await act(async () => {
      resolvePost(jsonResponse({ outbox_id: 'ob-2' }));
    });
    expect(screen.getByRole('status')).toHaveTextContent(/generating/i);
  });

  it('InlineGeneratePanel mounted with resumeGenerating renders Generating… without a click', () => {
    // D-C: the state survives a page refresh, so the server-rendered row opens
    // straight into the polling rendering.
    vi.useFakeTimers();
    render(<InlineGeneratePanel reviewId={REVIEW_ID} resumeGenerating />);

    expect(screen.getByRole('status')).toHaveTextContent(/generating/i);
    expect(screen.queryByRole('button', { name: /^generate$/i })).not.toBeInTheDocument();
  });

  it('InlineGeneratePanel shows the draft with its AI disclosure and both actions when ready', async () => {
    await renderReadyDraft();

    expect(screen.getByText('Thanks for the kind words!')).toBeInTheDocument();
    expect(screen.getByText(/draft generated by ai/i)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: /approve & post/i })).toBeInTheDocument();
    expect(screen.getByRole('button', { name: /^edit$/i })).toBeInTheDocument();
  });

  it('InlineGeneratePanel Edit opens a textarea seeded with the draft and Cancel restores it', async () => {
    await renderReadyDraft('Original draft');

    fireEvent.click(screen.getByRole('button', { name: /^edit$/i }));
    const textarea = screen.getByRole('textbox', { name: /edit the draft reply/i });
    expect(textarea).toHaveValue('Original draft');
    expect(textarea).toHaveAttribute('maxlength', '2000');

    fireEvent.change(textarea, { target: { value: 'My own words' } });
    expect(screen.getByRole('textbox', { name: /edit the draft reply/i })).toHaveValue(
      'My own words',
    );

    fireEvent.click(screen.getByRole('button', { name: /cancel/i }));
    expect(screen.getByText('My own words')).toBeInTheDocument();
    expect(screen.queryByRole('textbox')).not.toBeInTheDocument();
  });

  it('InlineGeneratePanel disables Save & post on a whitespace-only edit', async () => {
    await renderReadyDraft('Original draft');

    fireEvent.click(screen.getByRole('button', { name: /^edit$/i }));
    fireEvent.change(screen.getByRole('textbox', { name: /edit the draft reply/i }), {
      target: { value: '   ' },
    });

    expect(screen.getByRole('button', { name: /save & post/i })).toBeDisabled();
    expect(fetchMock).toHaveBeenCalledTimes(2);
  });

  it('InlineGeneratePanel shows Posting… then the server confirmation after Approve & post', async () => {
    await renderReadyDraft();
    let resolvePost!: (r: Response) => void;
    fetchMock.mockReturnValueOnce(
      new Promise<Response>((res) => {
        resolvePost = res;
      }),
    );

    await act(async () => {
      fireEvent.click(screen.getByRole('button', { name: /approve & post/i }));
    });
    expect(screen.getByRole('status')).toHaveTextContent(/posting/i);

    await act(async () => {
      resolvePost(jsonResponse({ success: true, message: 'Reply queued for Google.' }));
    });
    expect(screen.getByRole('status')).toHaveTextContent('Reply queued for Google.');
    expect(screen.queryByRole('button')).not.toBeInTheDocument();
  });

  it('InlineGeneratePanel posts an edited draft through Save & post', async () => {
    await renderReadyDraft('Original draft');
    fetchMock.mockResolvedValueOnce(jsonResponse({ success: true, message: 'Edited reply queued.' }));

    fireEvent.click(screen.getByRole('button', { name: /^edit$/i }));
    fireEvent.change(screen.getByRole('textbox', { name: /edit the draft reply/i }), {
      target: { value: 'My own words' },
    });
    await act(async () => {
      fireEvent.click(screen.getByRole('button', { name: /save & post/i }));
    });

    expect(screen.getByRole('status')).toHaveTextContent('Edited reply queued.');
    const editCall = fetchMock.mock.calls.at(-1)!;
    expect(editCall[0]).toBe(`/api/dashboard/reviews/${REVIEW_ID}/edit`);
    expect(JSON.parse((editCall[1] as RequestInit).body as string)).toEqual({
      editedText: 'My own words',
    });
  });

  it('InlineGeneratePanel renders a failure as an alert whose Try again returns to Generate', async () => {
    fetchMock.mockResolvedValueOnce(
      jsonResponse(
        { error: 'regen_limit_reached', message: 'Daily regenerate limit reached for this review.' },
        { ok: false, status: 429 },
      ),
    );
    render(<InlineGeneratePanel reviewId={REVIEW_ID} resumeGenerating={false} />);

    await act(async () => {
      fireEvent.click(screen.getByRole('button', { name: /^generate$/i }));
    });
    expect(screen.getByRole('alert')).toHaveTextContent(
      'Daily regenerate limit reached for this review.',
    );

    fireEvent.click(screen.getByRole('button', { name: /try again/i }));
    expect(screen.getByRole('button', { name: /^generate$/i })).toBeInTheDocument();
  });
});
